/**
 * Default constitutions / task prompts for NaHaber AI Newsroom personas.
 * Fully editable from Admin after seed; never hard-code as sole runtime source of truth.
 *
 * Personas are AI editors / AI columnists — not human employees. No fake credentials.
 */

import type {
  AiEditorCapabilities,
  AiEditorLocalConfig,
  AiEditorTask,
  AiModelAssignment,
  AiPersonaType,
  AiPromptType,
} from '@/types/aiEditor'
import { DEFAULT_AI_CAPABILITIES } from '@/types/aiEditor'

export interface SeedEditorSpec {
  slug: string
  name: string
  title: string
  shortBio: string
  bio: string
  columnName: string | null
  primarySpecialization: string
  specializations: string[]
  categoryIds: string[]
  capabilities: Partial<AiEditorCapabilities>
  prompts: Partial<Record<AiPromptType, string>>
  modelAssignments?: Partial<Record<AiEditorTask, AiModelAssignment>>
  personaType: AiPersonaType
  desk: string
  editorialMission?: string
  tone?: string
  temperature?: number
  fallbackEditorSlug?: string | null
  localConfig?: AiEditorLocalConfig | null
  /** Default true; false for internal SEO/copy/verification agents. */
  assignableForNews?: boolean
}

